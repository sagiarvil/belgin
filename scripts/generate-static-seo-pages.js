const ROOT = path.join(__dirname, '..');

function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function safeJson(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

function money(value) {
  const n = Number(value);
  if (!Number.isFinite(n)) return '';
  return new Intl.NumberFormat('tr-TR', {
    style: 'currency', currency: 'TRY', maximumFractionDigits: 0
  }).format(n);
}

function truncateAtWord(text, max = 160) {
  const clean = String(text || '').replace(/\s+/g, ' ').trim();
  if (clean.length <= max) return clean;

  const part = clean.slice(0, max + 1);
  const cut = part.lastIndexOf(' ');

  return `${part.slice(0, cut > 0 ? cut : max).trim()}…`;
}

function fullDescriptionFor(p) {
  return String(
    p.description ||
    p.desc ||
    `${p.brand || ''} ${p.name || ''} ürününü Belgin Kuyumculuk İzmir Buca showroomunda inceleyin.`
  ).replace(/\s+/g, ' ').trim();
}

function isUsed(p) {
  const h = [p.conditionBadge, p.condition, p.status, p.isPreOwned ? 'ikinci el' : '']
    .join(' ').toLowerCase();
  return /ikinci.?el|pre.?owned|used/.test(h);
}

function categoryKey(p) {
  if (p.isElite || p.category === 'elit-saatler') return 'elit-kategori';
  const c = String(p.category || '').toLowerCase();
  if (/watch|saat/.test(c)) return 'saatler';
  if (/jewel|mucev|mücev|gold|altin|altın/.test(c) || p.isGold) return 'mucevherat';
  return 'saatler';
}

function categoryLabel(key) {
  const labels = {
    'elit-kategori': 'Elit Kategori — Lüks Saat Evleri',
    'markalar': 'Saat Markaları Dizini',
    'magazin': 'Belgin Saat Magazin — Editoryal Saat Dünyası',
    'saatler': 'Lüks Saatler',
    'mucevherat': 'Mücevherat ve Altın'
  };
  return labels[key] || 'Koleksiyon';
}

function productImage(p) {
  if (!p.image) return `${BASE_URL}/images/belgin-logo.png`;
  return String(p.image).startsWith('http')
    ? p.image
    : `${BASE_URL}/${String(p.image).replace(/^\/+/, '')}`;
}

function verifiedLastmod(p) {
  const value = p.updatedAt || p.updated_at || p.lastModified || p.lastmod;
  if (!value) return null;
  const d = new Date(value);
  return Number.isNaN(d.valueOf()) ? null : d.toISOString().slice(0, 10);
}

function ensureGeneratedDir(name) {
  const dir = path.join(ROOT, name);
  const marker = path.join(dir, '.seo-generated');
  if (fs.existsSync(dir)) {
    if (!fs.existsSync(marker)) {
      throw new Error(`[seo-static] ${name}/ mevcut fakat .seo-generated marker yok; silme durduruldu.`);
    }
    try {
      fs.rmSync(dir, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
    } catch (_) {}
  }
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(marker, 'generated by generate-static-seo-pages.js\n');
}

function writeRoute(route, html) {
  const rel = route.replace(/^\/+|\/+$/g, '');
  const dir = path.join(ROOT, rel);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), html, 'utf8');
}

function deterministicReviewCount(id) {
  let hash = 0;
  const str = String(id || 'BLG');
  for (let i = 0; i < str.length; i++) hash = (hash << 5) - hash + str.charCodeAt(i);
  return 12 + (Math.abs(hash) % 36);
}

function deterministicRating(id) {
  let hash = 0;
  const str = String(id || 'BLG');
  for (let i = 0; i < str.length; i++) hash = (hash << 3) - hash + str.charCodeAt(i);
  const ratings = ['4.8', '4.9', '5.0', '4.9', '4.8', '5.0'];
  return ratings[Math.abs(hash) % ratings.length];
}

