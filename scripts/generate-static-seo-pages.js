function buildRouteMap() {
  const map = {};
  for (const p of products) map[String(p.id)] = productRoute(p);
  fs.writeFileSync(path.join(ROOT, 'js', 'seo-route-map.js'),
    `window.SEO_ROUTE_MAP = Object.freeze(${JSON.stringify(map, null, 2)});\nwindow.SEO_CATEGORY_ROUTES = Object.freeze(${JSON.stringify(CATEGORY_ROUTES, null, 2)});\n`, 'utf8');
}

function main() {
  if (!Array.isArray(products) || products.length === 0) throw new Error('[seo-static] PRODUCTS boş.');
  ['urun','elit-kategori','markalar','magazin','saatler','mucevherat'].forEach(ensureGeneratedDir);
  
  const indexHtmlPath = path.join(ROOT, 'index.html');
  const indexHtml = fs.readFileSync(indexHtmlPath, 'utf8');

  const seen = new Set();
  for (const p of products) {
    const route = productRoute(p);
    if (seen.has(route)) throw new Error(`Duplicate product route: ${route}`);
    seen.add(route);
    writeRoute(route, renderProductPage(p, indexHtml));
  }
  for (const key of ['elit-kategori','markalar','magazin','saatler','mucevherat']) {
    writeRoute(CATEGORY_ROUTES[key], renderCategoryPage(key, products.filter(p => categoryKey(p) === key), indexHtml));
  }
  buildRouteMap();
  console.log(`[seo-static] ${products.length} ürün sayfası ve kategori sayfaları üretildi.`);
}

if (require.main === module) {
  main();
}

